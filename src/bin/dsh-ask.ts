#!/usr/bin/env node

/**
 * Explicit shell-integration installer for dsh-ask.
 * It owns only generated integration files in a dedicated configuration
 * location and never rewrites a user's primary shell configuration.
 *
 * @module @dsh-local/dsh-ask/bin
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'

const TEMPLATE_DIRECTORY = new URL('../templates/', import.meta.url)

/** Metadata needed to install one shell's generated integration file. */
interface ShellIntegration {
  /** Human-readable shell name for terminal output. */
  readonly displayName: string
  /** File name relative to {@link TEMPLATE_DIRECTORY}. */
  readonly template: string
  /** First line that identifies files generated by this integration. */
  readonly generatedMarker: string
  /** Return the generated-file destination for this shell. */
  target(configHome: string): string
  /** Return the command that activates the file in the current shell. */
  sourceCommand(target: string): string
}

/**
 * Shell integrations supported by this binary.
 *
 * Add a template under `src/templates/` and one entry here to support another
 * shell without embedding its syntax in TypeScript.
 */
const SHELL_INTEGRATIONS = {
  fish: {
    displayName: 'Fish',
    template: 'fish.fish',
    generatedMarker: '# dsh-ask fish integration; generated by dsh-ask init fish.',
    target: (configHome: string): string => join(configHome, 'fish', 'conf.d', 'zz-dsh-ask.fish'),
    sourceCommand: (target: string): string => `source ${target}`,
  },
  bash: {
    displayName: 'Bash',
    template: 'bash.bash',
    generatedMarker: '# dsh-ask bash integration; generated by dsh-ask init bash.',
    target: (configHome: string): string => join(configHome, 'dsh-ask', 'bash-command-not-found.bash'),
    sourceCommand: (target: string): string => `source ${target}`,
  },
  zsh: {
    displayName: 'Zsh',
    template: 'zsh.zsh',
    generatedMarker: '# dsh-ask zsh integration; generated by dsh-ask init zsh.',
    target: (configHome: string): string => join(configHome, 'dsh-ask', 'zsh-command-not-found.zsh'),
    sourceCommand: (target: string): string => `source ${target}`,
  },
  powershell: {
    displayName: 'PowerShell (experimental)',
    template: 'powershell.ps1',
    generatedMarker: '# dsh-ask PowerShell integration; generated by dsh-ask init powershell.',
    target: (configHome: string): string => join(configHome, 'dsh-ask', 'powershell-command-not-found.ps1'),
    sourceCommand: (target: string): string => `. '${target.replaceAll("'", "''")}'`,
  },
} satisfies Record<string, ShellIntegration>

type SupportedShell = keyof typeof SHELL_INTEGRATIONS

/** Determine whether a command-line shell name has an installer. */
function isSupportedShell(shell: string | undefined): shell is SupportedShell {
  return shell !== undefined && Object.hasOwn(SHELL_INTEGRATIONS, shell)
}

/** Read and validate a shell's package-provided template. */
function readTemplate(integration: ShellIntegration): string {
  const path = new URL(integration.template, TEMPLATE_DIRECTORY)
  const template = readFileSync(path, 'utf8')
  if (!template.startsWith(integration.generatedMarker)) {
    throw new Error(`shell template has an invalid generated marker: ${path}`)
  }
  return template
}

/** Print binary usage. */
function usage(): void {
  const supportedShells = Object.entries(SHELL_INTEGRATIONS)
    .map(([shell, integration]) => `  ${shell.padEnd(10)} Install the ${integration.displayName} command-not-found integration.`)
    .join('\n')
  process.stdout.write(`Usage: dsh-ask init <shell>\n\nSupported shells:\n${supportedShells}\n\nShell integrations are generated from package templates. The generated file routes unknown interactive commands to:\n  dsh --profile \${DSH_ASK_PROFILE:-ask} -- <question>\n`)
}

/** Install the generated configuration file for one supported shell. */
function installShell(shell: SupportedShell): void {
  const integration = SHELL_INTEGRATIONS[shell]
  const configHome = process.env.XDG_CONFIG_HOME ?? join(homedir(), '.config')
  const target = integration.target(configHome)
  if (existsSync(target) && !readFileSync(target, 'utf8').startsWith(integration.generatedMarker)) {
    throw new Error(`refusing to overwrite non-dsh-ask file: ${target}`)
  }
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, readTemplate(integration), { encoding: 'utf8', mode: 0o644 })
  process.stdout.write(`dsh-ask: installed ${integration.displayName} integration at ${target}\n`)
  process.stdout.write(`dsh-ask: run \`${integration.sourceCommand(target)}\` to enable it in this shell.\n`)
}

const [command, shell] = process.argv.slice(2)
if (command === 'init' && isSupportedShell(shell)) {
  installShell(shell)
} else if (command === '--help' || command === '-h' || command === undefined) {
  usage()
} else {
  usage()
  process.exitCode = 2
}
